@testable import CommonLibraryCore
import Partout
import Testing
import Foundation

struct WireGuardQuickParserTests {
    private static let privateKey = base64Key(0x11)

    private static let peerKey = base64Key(0x22)

    private static let presharedKey = base64Key(0x33)

    private static func base64Key(_ seed: UInt8) -> String {
        Data((0..<32).map { _ in seed }).base64EncodedString()
    }

    private let sut = WireGuardQuickParser()

    private var validContents: String {
        """
        # Generated by wg tool
        [Interface]
        PrivateKey = \(Self.privateKey)
        Address = 10.0.0.2/32, 10.0.1.2/24
        DNS = 1.1.1.1, example.com
        MTU = 1420

        [Peer]
        PublicKey = \(Self.peerKey)
        PresharedKey = \(Self.presharedKey)
        AllowedIPs = 0.0.0.0/0, ::/0
        Endpoint = vpn.example.com:51820
        PersistentKeepalive = 25
        """
    }

    @Test
    func givenValidConfiguration_whenParse_thenBuildsConfiguration() throws {
        let builder = try sut.configurationBuilder(fromContents: validContents)
        #expect(builder.interface.privateKey == Self.privateKey)
        #expect(builder.interface.addresses == ["10.0.0.2/32", "10.0.1.2/24"])
        #expect(builder.interface.mtu == 1420)
        #expect(builder.interface.dns?.servers == ["1.1.1.1"])
        #expect(builder.interface.dns?.domains == ["example.com"])
        #expect(builder.peers.count == 1)
        let peer = try #require(builder.peers.first)
        #expect(peer.publicKey == Self.peerKey)
        #expect(peer.preSharedKey == Self.presharedKey)
        #expect(peer.allowedIPs == ["0.0.0.0/0", "::/0"])
        #expect(peer.endpoint == "vpn.example.com:51820")
        #expect(peer.keepAlive == 25)
    }

    @Test
    func givenValidConfiguration_whenBuildModule_thenSucceeds() throws {
        let module = try sut.module(fromContents: validContents)
        #expect(module.moduleType == .WireGuard)
    }

    @Test
    func givenMissingInterface_whenParse_thenThrows() {
        let contents = """
        [Peer]
        PublicKey = \(Self.peerKey)
        """
        #expect(throws: ABI.AppError.self) {
            try sut.configurationBuilder(fromContents: contents)
        }
    }

    @Test
    func givenMissingPrivateKey_whenParse_thenThrows() {
        let contents = """
        [Interface]
        Address = 10.0.0.2/32

        [Peer]
        PublicKey = \(Self.peerKey)
        """
        #expect(throws: ABI.AppError.self) {
            try sut.configurationBuilder(fromContents: contents)
        }
    }

    @Test
    func givenInvalidKey_whenParse_thenThrows() {
        let contents = """
        [Interface]
        PrivateKey = not-base64!!
        """
        #expect(throws: ABI.AppError.self) {
            try sut.configurationBuilder(fromContents: contents)
        }
    }

    @Test
    func givenShortKey_whenParse_thenThrows() {
        let contents = """
        [Interface]
        PrivateKey = \(Data((0..<16).map { _ in UInt8(1) }).base64EncodedString())
        """
        #expect(throws: ABI.AppError.self) {
            try sut.configurationBuilder(fromContents: contents)
        }
    }

    @Test
    func givenDuplicatedPeerKey_whenParse_thenThrows() {
        let contents = """
        [Interface]
        PrivateKey = \(Self.privateKey)

        [Peer]
        PublicKey = \(Self.peerKey)

        [Peer]
        PublicKey = \(Self.peerKey)
        """
        #expect(throws: ABI.AppError.self) {
            try sut.configurationBuilder(fromContents: contents)
        }
    }

    @Test
    func givenUnrecognizedKeys_whenParse_thenIgnoresThem() throws {
        let contents = """
        [Interface]
        PrivateKey = \(Self.privateKey)
        ListenPort = 51820
        FwMark = 0x1234

        [Peer]
        PublicKey = \(Self.peerKey)
        Table = off
        """
        let builder = try sut.configurationBuilder(fromContents: contents)
        #expect(builder.peers.count == 1)
    }

    @Test
    func givenFieldsBeforePublicKey_whenParse_thenFieldsAttachToTheirPeer() throws {
        let contents = """
        [Interface]
        PrivateKey = \(Self.privateKey)

        [Peer]
        AllowedIPs = 10.0.0.0/24
        Endpoint = first.example.com:51820
        PublicKey = \(Self.peerKey)
        PresharedKey = \(Self.presharedKey)
        PersistentKeepalive = 25
        """
        let builder = try sut.configurationBuilder(fromContents: contents)
        #expect(builder.peers.count == 1)
        let peer = try #require(builder.peers.first)
        #expect(peer.publicKey == Self.peerKey)
        #expect(peer.preSharedKey == Self.presharedKey)
        #expect(peer.allowedIPs == ["10.0.0.0/24"])
        #expect(peer.endpoint == "first.example.com:51820")
        #expect(peer.keepAlive == 25)
    }

    @Test
    func givenMultiplePeersWithTrailingFields_whenParse_thenFieldsAttachToCorrectPeer() throws {
        let otherKey = Self.base64Key(0x44)
        let contents = """
        [Interface]
        PrivateKey = \(Self.privateKey)

        [Peer]
        PublicKey = \(Self.peerKey)
        Endpoint = first.example.com:51820

        [Peer]
        PublicKey = \(otherKey)
        Endpoint = second.example.com:51820
        """
        let builder = try sut.configurationBuilder(fromContents: contents)
        #expect(builder.peers.count == 2)
        #expect(builder.peers[0].endpoint == "first.example.com:51820")
        #expect(builder.peers[1].endpoint == "second.example.com:51820")
    }

    @Test
    func givenDomainOnlyDNS_whenParse_thenUsesFallbackServers() throws {
        let contents = """
        [Interface]
        PrivateKey = \(Self.privateKey)
        DNS = example.com, other.example.org

        [Peer]
        PublicKey = \(Self.peerKey)
        """
        let builder = try sut.configurationBuilder(fromContents: contents)
        let dns = try #require(builder.interface.dns)
        #expect(!dns.servers.isEmpty)
        #expect(dns.domains == ["example.com", "other.example.org"])
    }

    @Test
    func givenHexLikeDomain_whenParse_thenTreatedAsDomain() throws {
        let contents = """
        [Interface]
        PrivateKey = \(Self.privateKey)
        DNS = cafe.de

        [Peer]
        PublicKey = \(Self.peerKey)
        """
        let builder = try sut.configurationBuilder(fromContents: contents)
        let dns = try #require(builder.interface.dns)
        #expect(dns.servers == ["1.1.1.1", "8.8.8.8"])
        #expect(dns.domains == ["cafe.de"])
    }

    @Test
    func givenNoPeers_whenParse_thenThrows() {
        let contents = """
        [Interface]
        PrivateKey = \(Self.privateKey)
        """
        #expect(throws: ABI.AppError.self) {
            try sut.configurationBuilder(fromContents: contents)
        }
    }
}
